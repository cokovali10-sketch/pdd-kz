const resources = { ru: { translation: ru }, kk: { translation: kk }, en: { translation: en } } as const;

export const SUPPORTED_LOCALES: Locale[] = ['ru', 'kk', 'en'];

export function detectLocale(): Locale {
  try {
    const stored = localStorage.getItem('jb.locale');
    if (stored === 'ru' || stored === 'kk' || stored === 'en') return stored;
  } catch {
    /* ignore */
  }
  const nav = typeof navigator !== 'undefined' ? navigator.language.toLowerCase() : 'ru';
  if (nav.startsWith('kk')) return 'kk';
  if (nav.startsWith('en')) return 'en';
  return 'ru';
}

const initial = detectLocale();

if (typeof document !== 'undefined') {
  document.documentElement.lang = initial;
  document.documentElement.setAttribute('data-locale', initial);
}

void i18n.use(initReactI18next).init({
  resources,
  lng: initial,
  fallbackLng: 'ru',
  interpolation: { escapeValue: false },
  returnNull: false,
});

export function setLocale(locale: Locale): void {
  void i18n.changeLanguage(locale);
  try {
    localStorage.setItem('jb.locale', locale);
  } catch {
    /* ignore */
  }
  if (typeof document !== 'undefined') {
    document.documentElement.lang = locale;
    document.documentElement.setAttribute('data-locale', locale);
  }
}

